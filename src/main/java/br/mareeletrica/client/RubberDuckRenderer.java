package br.mareeletrica.client;

import br.mareeletrica.MareEletrica;
import br.mareeletrica.RubberDuck;
import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.math.Axis;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.RenderType;
import net.minecraft.client.renderer.entity.EntityRenderer;
import net.minecraft.client.renderer.entity.EntityRendererProvider;
import net.minecraft.client.renderer.item.ItemProperties;
import net.minecraft.client.renderer.texture.OverlayTexture;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.util.Mth;

/** 0.88.0: the rubber duck — round body, raised tail, big head with eyes and an orange beak; squished when squeezed. */
public final class RubberDuckRenderer extends EntityRenderer<RubberDuck.Toy> {
 static final ResourceLocation[] TEX=new ResourceLocation[4];
 static{for(int i=0;i<4;i++)TEX[i]=ResourceLocation.fromNamespaceAndPath(MareEletrica.ID,"textures/entity/rubber_duck_"+i+".png");}
 static ModelPart model;
 /** generated by tools/rubber_duck_gen.py (keep the boxes in sync with it) */
 static ModelPart build(){
  var mesh=new MeshDefinition();var r=mesh.getRoot();
  r.addOrReplaceChild("body",CubeListBuilder.create().texOffs(0,0).addBox(-3F,19F,-3.5F,6,5,7),PartPose.ZERO);
  r.addOrReplaceChild("chest",CubeListBuilder.create().texOffs(26,0).addBox(-2.5F,18.6F,-4.6F,5,4,1.2F),PartPose.ZERO);
  r.addOrReplaceChild("tail",CubeListBuilder.create().texOffs(0,12).addBox(-1.5F,17.6F,3F,3,2.6F,2),PartPose.offsetAndRotation(0,0,0,-.25F,0,0));
  r.addOrReplaceChild("head",CubeListBuilder.create().texOffs(12,12).addBox(-2.2F,13.6F,-4.4F,4.4F,5,4.4F),PartPose.ZERO);
  r.addOrReplaceChild("beak",CubeListBuilder.create().texOffs(44,16).addBox(-1.5F,16.4F,-6.6F,3,1.4F,2.3F),PartPose.ZERO);
  r.addOrReplaceChild("wing_l",CubeListBuilder.create().texOffs(40,0).addBox(-3.5F,19.7F,-2F,.6F,2.8F,4.6F),PartPose.ZERO);
  r.addOrReplaceChild("wing_r",CubeListBuilder.create().texOffs(40,8).addBox(2.9F,19.7F,-2F,.6F,2.8F,4.6F),PartPose.ZERO);
  return LayerDefinition.create(mesh,64,32).bakeRoot();}
 public RubberDuckRenderer(EntityRendererProvider.Context c){super(c);shadowRadius=.18F;}
 @Override public ResourceLocation getTextureLocation(RubberDuck.Toy t){return TEX[Mth.clamp(t.variant(),0,3)];}
 @Override public void render(RubberDuck.Toy t,float yaw,float pt,PoseStack pose,MultiBufferSource buf,int light){
  if(model==null)model=build();
  pose.pushPose();
  pose.mulPose(Axis.YP.rotationDegrees(180F-Mth.rotLerp(pt,t.yRotO,t.getYRot())));
  float sq=Mth.lerp(pt,t.squishO,t.squishV);
  float wob=t.floating()?Mth.sin((t.tickCount+pt)*.12F+t.getId())*4F:0F;
  pose.mulPose(Axis.ZP.rotationDegrees(wob));pose.mulPose(Axis.XP.rotationDegrees(wob*.6F));
  pose.scale(.6F,.6F,.6F);pose.scale(1F+sq*.18F,1F-sq*.28F,1F+sq*.18F);
  pose.scale(-1F,-1F,1F);pose.translate(0,-1.501F,0);
  model.render(pose,buf.getBuffer(RenderType.entityCutoutNoCull(getTextureLocation(t))),light,OverlayTexture.NO_OVERLAY);
  pose.popPose();
  super.render(t,yaw,pt,pose,buf,light);}
 public static void properties(){
  ItemProperties.register(RubberDuck.ITEM.get(),ResourceLocation.fromNamespaceAndPath(MareEletrica.ID,"variant"),(s,l,e,i)->RubberDuck.variant(s)/4F);}
}
